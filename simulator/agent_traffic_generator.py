class AgentTrafficSimulator:
    """Generates synthetic multi-agent traffic and threat traces."""

    @classmethod
    def generate_single_event(cls, force_attack: bool = False) -> Dict[str, Any]:
        """Generates a single realistic agent transaction."""
        agent_cfg = random.choice(AGENTS)
        is_attack = force_attack or (random.random() < 0.22)  # 22% incident rate in simulation

        if is_attack:
            prompt = random.choice(agent_cfg["attack_prompts"])
            tool = random.choice(agent_cfg["tools"])
            input_tokens = random.randint(300, 1800)
            output_tokens = random.randint(150, 900)
            latency = random.uniform(250.0, 1100.0)
            response = "Simulated response generated by enterprise agent."
        else:
            prompt = random.choice(agent_cfg["normal_prompts"])
            tool = random.choice(agent_cfg["tools"]) if random.random() > 0.3 else None
            input_tokens = random.randint(80, 450)
            output_tokens = random.randint(40, 300)
            latency = random.uniform(60.0, 350.0)
            response = f"Successfully processed request for: {prompt[:35]}..."

        tool_input = f"{{\"param\": \"{random.randint(1000, 9999)}\"}}" if tool else None
        tool_output = "{\"status\": \"OK\"}" if tool else None

        result = AgentInterceptor.process_agent_step(
            agent_name=agent_cfg["name"],
            agent_role=agent_cfg["role"],
            model_name=agent_cfg["model"],
            prompt=prompt,
            response=response,
            tool_name=tool,
            tool_input=tool_input,
            tool_output=tool_output,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            latency_ms=latency
        )
        return result

    @classmethod
    def seed_historical_telemetry(cls, count: int = 150):
        """Pre-seeds the Exasol database with realistic telemetry for instant demo readiness."""
        for _ in range(count):
            cls.generate_single_event()
